-- Configuration only. No balances, prices, quotas, or coupon issuance seeded.
CREATE TABLE IF NOT EXISTS point_exchange_catalog (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 coupon_id BIGINT UNSIGNED NOT NULL,
 publication_revision BIGINT UNSIGNED NOT NULL,
 pool_revision BIGINT UNSIGNED NOT NULL,
 terms_snapshot JSON NOT NULL,
 points_cost INT UNSIGNED NOT NULL,
 per_owner_limit INT UNSIGNED NOT NULL,
 source_note VARCHAR(256) NOT NULL,
 valid_from DATETIME NOT NULL,
 valid_to DATETIME NOT NULL,
 revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
 status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
 rule_version VARCHAR(32) NOT NULL DEFAULT 'R8A_EXCHANGE_V1',
 created_by BIGINT UNSIGNED NOT NULL,
 submission_key CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 submission_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 creation_result JSON DEFAULT NULL,
 created_at DATETIME NOT NULL,
 published_at DATETIME DEFAULT NULL,
 published_coupon BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN status='PUBLISHED' THEN coupon_id ELSE NULL END) STORED,
 PRIMARY KEY(id),
 UNIQUE KEY uk_point_catalog_submission(created_by,submission_key),
 UNIQUE KEY uk_point_catalog_published(published_coupon),
 KEY idx_point_catalog_coupon(coupon_id,status,id),
 CONSTRAINT ck_point_catalog_cost CHECK(points_cost BETWEEN 1 AND 1000000),
 CONSTRAINT ck_point_catalog_limit CHECK(per_owner_limit BETWEEN 1 AND 1000000),
 CONSTRAINT ck_point_catalog_window CHECK(valid_to>valid_from),
 CONSTRAINT ck_point_catalog_status CHECK(status IN ('DRAFT','PUBLISHED','STOPPED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
